/** 시연용 퍼소나. 데이터는 `@/data/common/personas`. */

export type Persona = {
  id: string;
  /**
   * 이름 — 카드 · 회원증 · 「○○ 님을 위한 오늘의 상품」 어디서나 이것 그대로다.
   * 전에는 홈이 성을 뗀 이름(「상현 님」)을 따로 들고 있었는데, 화면마다 부르는
   * 말이 달라 하나로 모았다(감수 지적). 가입 때 넣은 닉네임이 있으면 그것이
   * 이긴다(useUserName).
   */
  name: string;
  /** 「신규 가입」 · 「기존 회원」 */
  tag: string;
  /** 카드 아래 한 줄. */
  line: string;
  /**
   * 온보딩부터 보는지.
   *
   * 아직 가입하지 않은 사람은 여는 화면부터 지나가고, 이미 쓰던 사람은 곧장
   * 홈으로 들어간다 — 퍼소나를 고르는 것이 곧 로그인을 대신한다.
   */
  fresh: boolean;
  /** 회원 등급. 블랙카드는 잠긴 것 없이 다 열려 있다. */
  tier: string;
  /**
   * MY 의 회원증 — 쓰던 사람은 검은 알루미늄 블랙카드, 막 가입한 사람은 보라
   * 플라스틱 체크카드(2093:6154 · 2093:6118). 입력정보의 구독(체크 / 신용 / 블랙)
   * 세 등급이 다 그려져 있어 초록 신용카드(2093:6082)도 고를 수 있다 — 아직
   * 신용 등급 퍼소나는 없다(사용자 결정: 디자인만 둔다).
   */
  card: "black" | "credit" | "check";
  /** 회원증 뒷면 사진. 가입 때 넣는 더미 사진과 같은 것이어야 같은 사람이다. */
  photo: string;
  /** 여태 뽑은 영수증 수 — 회원증 뒷면 Receipt 칸. 막 가입한 사람은 0. */
  receipts: number;
  /**
   * 관심 분야 — 가입 설문에서 고른 것(분야 id · 최대 둘, `menu.ts` fields).
   *
   * 홈 진열대 · 설문의 기본 선택 · MY 관심 카테고리 · 회원증 Likes 가 이것으로
   * 시작한다(surveyStore). 사람마다 달라야 진열대가 「그 사람을 위한」 것이다.
   */
  interests: string[];
  /**
   * 들고 시작하는 코인.
   *
   * 블랙카드로 다 열려 있는 사람과 오늘 막 가입한 사람의 지갑이 같으면, 두
   * 사람을 갈라 놓은 뜻이 없다 — 「코인이 모자라 못 여는」 경험은 신규 쪽에만
   * 있어야 한다.
   */
  coins: number;
  /**
   * 가챠 무료 쿠폰 — 들고 시작하는 장수.
   *
   * 블랙카드는 달마다 한 장이 나오고(한상현은 이달 것 한 장), 체크카드는 없다
   * — 한 판마다 코인 1개를 치른다(사용자 결정). 코인처럼 지갑(couponStore)이
   * 들고 있다가 쓰면 줄어든다.
   */
  coupons: number;
};
