/** 분야 한 칸 — 햄버거 메뉴의 카테고리 탭 · Figma 965:5950 */
export type Field = {
  id: string;
  name: string;
  /** 아래 줄에 붙는 세부 분류 */
  sub: string;
  /** 커뮤니티 카테고리와 같은 색 */
  color: string;
  /**
   * 분야 그림 — 시안 1968:6518(디자이너가 분야마다 그린 것). 분야 색의 옅은 톤으로
   * 칠해진 색 그림이라 `bg`(진한 600 톤) 나 검은 상자 위에 얹는다.
   */
  icon: string;
  /**
   * 그림 뒤에 까는 분야색 — 피그마 SubColor 토큰의 500(사용자 지시 — 옅게 탄 네모는
   * 그림이 안 보였고 600 은 너무 진했다). 값의 출처는 menu.ts 의 fields 에.
   */
  bg: string;
  /**
   * 카드 안 오른쪽, 선반 위에 세워 두는 상품 그림 — 홈 진열대의 켜진(컬러) 그림을 그대로
   * 쓴다(사용자 지시). 분야마다 하나씩: 사회 컵라면 · 역사 우유 · 과학 과자 ·
   * 문화 커피 · 생활 초콜릿.
   */
  product: string;
};

