/** 봉지 한 벌의 색. 몸통 · 테(접힌 자리와 이빨) · 가운데 띠. */
export type BagTone = { body: string; edge: string; label: string };

/**
 * 봉지에 쓰는 색 — 전부 스타일 가이드(551:2485)의 색 계단에서 가져온다.
 *
 * 노랑은 원래 그림이 쓰던 그대로(300 · 400 · 100)다. 나머지는 계단이 서로
 * 밝기가 달라 단계를 똑같이 맞추면(예: 분홍 300) 어두운 바탕에서 흰 봉지로
 * 보이므로, 노란 봉지와 비슷한 무게로 읽히는 단계를 하나씩 골랐다.
 */
export const BAG_TONES: BagTone[] = [
  { body: "#fbd16b", edge: "#fac139", label: "#fef7e6" }, // 노랑
  { body: "#b0abf0", edge: "#968feb", label: "#f2f1fc" }, // 보라
  { body: "#66bbeb", edge: "#33a5e5", label: "#e5f4fc" }, // 파랑
  { body: "#fbc9da", edge: "#f8a5c2", label: "#fef6f9" }, // 분홍
  { body: "#88e6c5", edge: "#66cda9", label: "#d6fff1" }, // 초록
  { body: "#d08581", edge: "#a9544f", label: "#f9dddc" }, // 밤색
];

/**
 * 서로 다른 색 `count` 벌을 아무렇게나 고른다 — 뽑을 때마다 다른 봉지가 돈다.
 *
 * 겹치지 않게 고르는 이유는 셋 중 둘이 같은 색이면 「세 개가 돈다」가 아니라
 * 「두 개가 돈다」로 보이기 때문이다.
 */
export function pickBagTones(count: number): BagTone[] {
  const pool = [...BAG_TONES];
  for (let i = pool.length - 1; i > 0; i -= 1) {
    const j = Math.floor(Math.random() * (i + 1));
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  return pool.slice(0, count);
}

/**
 * 가운데 띠의 왼쪽 그늘 — 띠보다 한 겹 어둡다.
 *
 * 원본이 띠(#fef7e6) 옆에 #ede6d6 을 두었는데, 채널마다 0.93 을 곱한 값이다.
 * 색마다 손으로 적어 두는 대신 그 비율을 그대로 쓴다.
 */
function shade(hex: string): string {
  const n = parseInt(hex.slice(1), 16);
  const dim = (channel: number) => Math.round(((n >> channel) & 0xff) * 0.93);
  return `rgb(${dim(16)} ${dim(8)} ${dim(0)})`;
}

